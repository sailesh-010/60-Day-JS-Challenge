let mouseover = document.querySelector('.mouseover');
mouseover.addEventListener('mouseover', function() {
    let mouseover1 = document.querySelector('.mouseover1');
    mouseover1.style.display = 'block';
})

let mouseLeave = document.querySelector('.mouseLeave');
mouseLeave.addEventListener('mouseleave', function() {
    let mouseLeave1 = document.querySelector('.mouseLeave1');
    mouseLeave1.style.display = 'block';
})
